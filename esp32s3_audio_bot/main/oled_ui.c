static i2c_master_dev_handle_t oled_handle = NULL;

static void send_cmd(uint8_t cmd) {
    if (!oled_handle) return;
    uint8_t data[2] = {0x00, cmd};
    i2c_master_transmit(oled_handle, data, 2, 1000);
}

static void send_data(uint8_t data) {
    if (!oled_handle) return;
    uint8_t buf[2] = {0x40, data};
    i2c_master_transmit(oled_handle, buf, 2, 1000);
}

static void oled_clear(void) {
    for (int y = 0; y < 8; y++) {
        send_cmd(0xB0 + y);
        send_cmd(0x00);
        send_cmd(0x10);
        for (int x = 0; x < 128; x++) send_data(0x00);
    }
}

void oled_ui_init(void) {
    ESP_LOGI(TAG, "Initializing native I2C OLED on SDA=%d SCL=%d", OLED_SDA_PIN, OLED_SCL_PIN);
    
    i2c_master_bus_config_t bus_config = {
        .i2c_port = I2C_NUM_0,
        .sda_io_num = OLED_SDA_PIN,
        .scl_io_num = OLED_SCL_PIN,
        .clk_source = I2C_CLK_SRC_DEFAULT,
        .glitch_ignore_cnt = 7,
        .flags.enable_internal_pullup = true,
    };
    i2c_master_bus_handle_t bus_handle;
    ESP_ERROR_CHECK(i2c_new_master_bus(&bus_config, &bus_handle));

    i2c_device_config_t dev_config = {
        .dev_addr_length = I2C_ADDR_BIT_LEN_7,
        .device_address = SSD1306_ADDR,
        .scl_speed_hz = 400000,
    };
    ESP_ERROR_CHECK(i2c_master_bus_add_device(bus_handle, &dev_config, &oled_handle));

    // Standard SSD1306 init sequence
    const uint8_t init_cmds[] = {
        0xAE, 0x20, 0x00, 0x40, 0xA1, 0xC8, 0xA6, 0xA8, 0x3F,
        0xD3, 0x00, 0xD5, 0x80, 0xD9, 0xF1, 0xDA, 0x12, 0xDB,
        0x40, 0x8D, 0x14, 0xAF
    };
    for (int i=0; i<sizeof(init_cmds); i++) send_cmd(init_cmds[i]);
    oled_clear();
}

void oled_ui_set_text(const char *line1, const char *line2) {
    oled_clear();
    const char *lines[2] = {line1 ? line1 : "", line2 ? line2 : ""};
    
    for (int l = 0; l < 2; l++) {
        // Draw each line on page 2 and 4 respectively
        int page = (l == 0) ? 2 : 5;
        send_cmd(0xB0 + page);
        send_cmd(0x00);
        send_cmd(0x10);
        
        const char *txt = lines[l];
        while (*txt) {
            char c = *txt++;
            if (c < 32 || c > 126) c = '?';
            const uint8_t *glyph = &font5x7[(c - 32) * 5];
            for (int i = 0; i < 5; i++) send_data(glyph[i]);
            send_data(0x00); // 1px spacing
        }
    }
    ESP_LOGI(TAG, "OLED Updated: %s | %s", lines[0], lines[1]);
}

extern const uint8_t geminieyes_bin_start[] asm("_binary_geminieyes_bin_start");
extern const uint8_t geminieyes_bin_end[]   asm("_binary_geminieyes_bin_end");

void oled_ui_draw_eyes(void) {
    size_t len = geminieyes_bin_end - geminieyes_bin_start;
    if (len != 1024) {
        ESP_LOGE(TAG, "Invalid geminieyes.bin length: %d", len);
        return;
    }
    for (int y = 0; y < 8; y++) {
        send_cmd(0xB0 + y);
        send_cmd(0x00);
        send_cmd(0x10);
        const uint8_t *row_data = &geminieyes_bin_start[y * 128];
        for (int x = 0; x < 128; x++) {
            send_data(row_data[x]);
        }
    }
}
